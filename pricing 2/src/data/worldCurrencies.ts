// Safe fallback getter for any currency code
export const getCurrencyConfig = (code: string | undefined): CurrencyConfig => {
  if (!code) return WORLD_CURRENCIES['NGN'];
  return WORLD_CURRENCIES[code.toUpperCase()] || WORLD_CURRENCIES['NGN'];
};

// Search helper across all world currencies
export const searchWorldCurrencies = (query: string): CurrencyConfig[] => {
  if (!query || !query.trim()) {
    return ALL_WORLD_CURRENCIES_LIST;
  }
  const clean = query.trim().toLowerCase();
  return ALL_WORLD_CURRENCIES_LIST.filter((curr) => {
    return (
      curr.code.toLowerCase().includes(clean) ||
      curr.name.toLowerCase().includes(clean) ||
      curr.symbol.toLowerCase().includes(clean) ||
      (curr.region && curr.region.toLowerCase().includes(clean)) ||
      (curr.flag && curr.flag.includes(clean))
    );
  });
};
