// Helper to format currency amount cleanly
const createFormatFunction = (item: Omit<WorldCurrencyItem, 'format'>) => {
  return (amountUSD: number): string => {
    const converted = amountUSD * item.exchangeRate;
    const isZeroDecimal =
      item.decimalPlaces === 0 ||
      converted >= 1000 ||
      ['NGN', 'KES', 'UGX', 'TZS', 'RWF', 'JPY', 'KRW', 'VND', 'IDR', 'CLP', 'COP', 'HUF'].includes(
        item.code
      );

    const formattedNumber = isZeroDecimal
      ? Math.round(converted).toLocaleString()
      : converted.toLocaleString(undefined, {
          minimumFractionDigits: 2,
          maximumFractionDigits: 2,
        });

    if (item.symbolPosition === 'suffix') {
      return `${formattedNumber} ${item.symbol}`;
    }
    // Prefix
    // Add space for alphanumeric symbols like "KSh ", "GH₵ ", "USh "
    const needsSpace = item.symbol.length > 2 || /^[A-Za-z]+$/.test(item.symbol);
    return `${item.symbol}${needsSpace ? ' ' : ''}${formattedNumber}`;
  };
};

// Build master WORLD_CURRENCIES record & array
export const WORLD_CURRENCIES: Record<string, CurrencyConfig> = RAW_WORLD_CURRENCIES.reduce(
  (acc, item) => {
    acc[item.code] = {
      ...item,
      format: createFormatFunction(item),
    };
    return acc;
  },
  {} as Record<string, CurrencyConfig>
);

export const ALL_WORLD_CURRENCIES_LIST: CurrencyConfig[] = RAW_WORLD_CURRENCIES.map((item) => ({
  ...item,
  format: createFormatFunction(item),
}));

